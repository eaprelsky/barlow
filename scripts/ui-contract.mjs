import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
const root = fileURLToPath(new URL('..', import.meta.url));
const port = 5196;
const vite = spawn(process.execPath, [root + '/node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', String(port), '--strictPort'], { cwd: root, stdio: 'ignore' });
let browser;
try {
  let ready = false;
  for (let i = 0; i < 60; i++) {
    try { if ((await fetch(`http://127.0.0.1:${port}`)).ok) { ready = true; break; } } catch {}
    await new Promise(r => setTimeout(r, 250));
  }
  if (!ready) throw new Error('Vite timeout');
  browser = await chromium.launch({ executablePath: process.env.BARLOW_BROWSER ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(10000);
  await page.addInitScript(() => localStorage.setItem('barlow.onboarding.v1', JSON.stringify({ invited: true, seen: { main: true } })));
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${port}`);
  await page.locator('[data-ob="mode-inst"]').first().click();
  const knob = page.locator('svg.knob').first();
  await knob.waitFor({ state: 'visible' });
  const value = () => knob.getAttribute('aria-valuenow').then(Number);
  const min = Number(await knob.getAttribute('aria-valuemin'));
  const max = Number(await knob.getAttribute('aria-valuemax'));
  await knob.focus(); await knob.press('End'); assert.equal(await value(), max);
  await knob.press('Home'); assert.equal(await value(), min);
  await page.keyboard.press('Control+z'); assert.equal(await value(), max);
  await page.keyboard.press('Control+Shift+z'); assert.equal(await value(), min);
  console.log('PASS knob keyboard and explicit undo/redo');
  await knob.press('Enter');
  const field = page.locator('.knob-wrap input').first();
  await field.fill(String(max)); await field.press('Escape');
  assert.equal(await value(), min);
  assert.equal(await knob.evaluate(el => document.activeElement === el), true);
  console.log('PASS Escape rolls back live numeric edit and restores focus');
  await knob.press('Enter'); await field.fill(''); await field.press('Tab');
  assert.equal(await value(), min);
  assert.equal(await knob.evaluate(el => document.activeElement === el), false);
  console.log('PASS empty numeric edit restores value, Tab leaves control');
  await knob.focus();
  await page.evaluate(async () => { const m = await import('/src/components/dialogs.ts'); void m.confirmDialog({ title: 'Контракт удаления', text: 'Проверка фокуса', danger: true, okLabel: 'удалить' }); });
  const dialog = page.getByRole('dialog', { name: 'Контракт удаления' });
  await dialog.waitFor({ state: 'visible' });
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'отмена');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'удалить');
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'отмена');
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
  assert.equal(await knob.evaluate(el => document.activeElement === el), true);
  console.log('PASS named modal, safe initial focus, focus trap, Escape and restoration');
  await page.keyboard.press('Control+k');
  const search = page.getByRole('textbox', { name: 'поиск звука' });
  await search.waitFor({ state: 'visible' });
  assert.equal(await search.evaluate(el => document.activeElement === el), true);
  assert.equal(await page.locator('button button').count(), 0);
  await search.fill('бас');
  assert.ok(await page.locator('.sb-apply').count() > 0);
  console.log('PASS keyboard sound search and separate apply/preview buttons');
  await page.locator('[data-ob="mode-sketch"]').first().click();
  const roll = page.locator('.roll-cols').first();
  const cell = roll.locator('.cell[tabindex="0"]');
  const beforeNote = await cell.getAttribute('aria-pressed');
  await cell.focus(); await cell.press('Enter');
  assert.notEqual(await cell.getAttribute('aria-pressed'), beforeNote);
  await page.keyboard.press('Control+z');
  assert.equal(await cell.getAttribute('aria-pressed'), beforeNote);
  await cell.press('ArrowRight');
  assert.equal(await cell.getAttribute('data-col'), '1');
  assert.equal(await roll.locator('.cell[tabindex="0"]').count(), 1);
  await cell.press('F2');
  assert.ok(await page.locator('.col-wrap.sel').count() > 0);
  await page.locator('.rate-sel').first().selectOption('custom');
  const ratio = page.getByRole('textbox', { name: 'своё отношение шага' }).first();
  await ratio.fill('7/5'); await ratio.press('Enter');
  assert.equal(await ratio.inputValue(), '1.4');
  console.log('PASS note keyboard editing/navigation/undo and rational rate entry');
  const saving = await page.evaluate(async () => {
    const m = await import('/src/storage.ts');
    const { defaultPatch } = await import('/src/music/defaultPatch.ts');
    const original = Storage.prototype.setItem;
    let writes = 0;
    Storage.prototype.setItem = function(key, value) { if (key === 'barlow.patch.v12') writes++; return original.call(this, key, value); };
    for (let i = 0; i < 20; i++) m.saveAutosave({ ...defaultPatch(), bpm: 120 + i });
    const beforeFlush = writes;
    m.flushAutosave();
    const afterFlush = writes;
    Storage.prototype.setItem = function() { throw new DOMException('quota test', 'QuotaExceededError'); };
    m.saveAutosave(defaultPatch()); m.flushAutosave();
    const failure = m.autosaveStatus();
    Storage.prototype.setItem = original;
    m.flushAutosave();
    return { beforeFlush, afterFlush, failure, recovered: m.autosaveStatus() };
  });
  assert.equal(saving.beforeFlush, 0); assert.equal(saving.afterFlush, 1);
  assert.equal(saving.failure.phase, 'error'); assert.equal(saving.recovered.phase, 'saved');
  console.log('PASS autosave coalescing, visible quota failure and retry');
  await page.screenshot({ path: root + '/tmp/ui-contract.png', fullPage: false });
  assert.deepEqual(errors, []);
  console.log('ui-contract: PASS');
} finally { await browser?.close(); vite.kill(); }
